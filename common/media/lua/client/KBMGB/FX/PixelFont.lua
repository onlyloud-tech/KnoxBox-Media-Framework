function PixelFont.draw(ctx, text, x, y, r, g, b, a, scale)
    scale = tonumber(scale) or 1
    a = tonumber(a) or 1.0
    r = tonumber(r) or 1.0
    g = tonumber(g) or 1.0
    b = tonumber(b) or 1.0
    local FW = PixelFont.W
    local FH = PixelFont.H
    local SP = PixelFont.SPACING
    local ox = x
    text = string.upper(tostring(text or ""))
    for i = 1, #text do
        local ch = text:sub(i, i)
        local glyph = PixelFont.GLYPHS[ch]
        if glyph then
            for row = 0, FH - 1 do
                for col = 0, FW - 1 do
                    if glyph[row * FW + col + 1] == 1 then
                        ctx.drawRect(ox + col * scale, y + row * scale, scale, scale, a, r, g, b)
                    end
                end
            end
        end
        ox = ox + (FW + SP) * scale
    end
end

function PixelFont.width(text, scale)
    scale = tonumber(scale) or 1
    local len = #tostring(text or "")
    if len == 0 then return 0 end
    return len * (PixelFont.W + PixelFont.SPACING) * scale - PixelFont.SPACING * scale
end

function PixelFont.centered(ctx, text, y, r, g, b, a, scale)
    local w = PixelFont.width(text, scale)
    local vw = ctx.virtualWidth or ctx.width or 320
    PixelFont.draw(ctx, text, math.floor((vw - w) / 2), y, r, g, b, a, scale)
end

function PixelFont.right(ctx, text, rightX, y, r, g, b, a, scale)
    local w = PixelFont.width(text, scale)
    PixelFont.draw(ctx, text, rightX - w, y, r, g, b, a, scale)
end

return PixelFont
